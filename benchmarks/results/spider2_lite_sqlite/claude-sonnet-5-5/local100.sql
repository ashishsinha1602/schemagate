WITH shah AS (
  SELECT PID FROM Person WHERE Name LIKE '%Shah%rukh Khan%' OR Name = 'Shah Rukh Khan'
),
shah_movies AS (
  SELECT DISTINCT MID FROM M_Cast WHERE PID IN (SELECT PID FROM shah)
),
n1 AS (
  SELECT DISTINCT PID FROM M_Cast
  WHERE MID IN (SELECT MID FROM shah_movies)
    AND PID NOT IN (SELECT PID FROM shah)
),
n1_movies AS (
  SELECT DISTINCT MID FROM M_Cast WHERE PID IN (SELECT PID FROM n1)
)
SELECT COUNT(DISTINCT PID) FROM M_Cast
WHERE MID IN (SELECT MID FROM n1_movies)
  AND PID NOT IN (SELECT PID FROM n1)
  AND PID NOT IN (SELECT PID FROM shah)