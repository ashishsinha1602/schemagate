"""Regenerate the hash-pinned requirement files CI and the Docker image install from.

    pip install uv && python scripts/lock_ci.py [name ...]

Every `pip install` in a workflow or the Dockerfile reads one of these with
`--require-hashes`, then installs schemagate itself with `--no-deps`, so no
dependency is fetched that a reviewer has not seen the hash of. Each file is
resolved once for every supported Python (`--universal`, from 3.10), so a
matrix job on 3.10 and one on 3.13
read the same file. Run it after changing pyproject.toml's dependencies, and
at least monthly or when Scorecard's Vulnerabilities check flags a pin --
Dependabot cannot regenerate universal, marker-split locks, so it is not
pointed at these files.
"""
from __future__ import annotations

import os
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / ".github" / "requirements"
#: the image build cannot see .github (.dockerignore), so its lock lives beside the build
DOCKER = ROOT / "docker" / "requirements.txt"
#: same reason for ClusterFuzzLite, which builds with the repository root as its context
FUZZ = ROOT / ".clusterfuzzlite" / "requirements.txt"

#: name -> (pyproject extras, extra requirement lines). Extras None = not from pyproject at all.
LOCKS = {
    "dev":            (["dev"], []),
    "dev-ai":         (["dev", "ai"], []),
    "dev-floor":      (["dev"], ["langchain-core==0.3.*"]),
    "dev-mssql":      (["dev"], ["pyodbc"]),
    "dev-mysql":      (["dev", "mcp"], ["pymysql"]),
    "dev-postgres":   (["dev", "postgres", "mcp"], []),
    "e2e-postgres":   (["mcp", "postgres"], ["uv"]),
    "e2e-mysql":      (["mcp", "mysql"], ["uv"]),
    "e2e-mssql":      (["mcp", "mssql"], ["uv"]),
    "e2e-oracle":     (["mcp", "oracle"], ["uv"]),
    # uniql-oracle.yml: UniQL's loader + scorer; the -oci one adds the OCI SDK for MODE=full only
    "uniql-oracle":     (["oracle"], ["python-dateutil", "func_timeout"]),
    "uniql-oracle-oci": (["oracle", "oci"], ["python-dateutil", "func_timeout"]),
    "docker":         (["databases", "ai", "mcp"], []),
    "fuzz":           ([], ["sqlglot>=25"]),     # run_query's parser layer is under test too
    "ruff":           (None, ["ruff==0.16.8"]),
    "markdown":       (None, ["markdown"]),
    "build":          (None, ["build"]),
}


def target(name: str) -> pathlib.Path:
    return {"docker": DOCKER, "fuzz": FUZZ}.get(name, OUT / f"{name}.txt")


def lock(name: str, extras, lines) -> None:
    out = target(name)
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        inputs = []
        if extras is not None:
            inputs.append(str(ROOT / "pyproject.toml"))
        if lines:
            extra = pathlib.Path(tmp) / f"{name}.in"
            extra.write_text("\n".join(lines) + "\n", "utf-8")
            inputs.append(str(extra))
        # --no-annotate: the "# via" notes would name machine-local temp files
        cmd = ["uv", "pip", "compile", *inputs, "--universal", "--python-version", "3.10",
               "--generate-hashes", "--no-header", "--no-annotate", "--quiet", "-o", str(out)]
        # existing pins are kept unless named here: LOCK_UPGRADE="uv requests" moves just those (a security fix)
        for pkg in os.environ.get("LOCK_UPGRADE", "").split():
            cmd += ["--upgrade-package", pkg]
        for e in extras or []:
            cmd += ["--extra", e]
        subprocess.run(cmd, check=True, cwd=ROOT)
    body = out.read_text("utf-8").rstrip("\n")
    out.write_text(f"# generated by scripts/lock_ci.py; do not edit by hand\n{body}\n", "utf-8")


def main() -> None:
    only = set(sys.argv[1:])
    for name, (extras, lines) in LOCKS.items():
        if not only or name in only:
            lock(name, extras, lines)
            print(f"locked {name} -> {target(name).relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
